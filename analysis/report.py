"""Structured outputs for Phase 2: a JSON summary and a written report.

The report is generated *from the computed numbers*, never typed in by hand: a
change in the data changes the report.
"""

from __future__ import annotations

import json
import math
import os

import numpy as np

from . import accuracy_targets


def _fmt(value, digits: int = 4) -> str:
    if value is None:
        return "-"
    if isinstance(value, (int, np.integer)):
        return str(int(value))
    if isinstance(value, float) and not math.isfinite(value):
        return "-"
    if isinstance(value, (float, np.floating)):
        if value != 0 and (abs(value) < 1e-2 or abs(value) >= 1e4):
            return f"{value:.{digits}e}"
        return f"{value:.{digits}g}"
    return str(value)


def _jsonable(obj):
    if isinstance(obj, dict):
        return {str(key): _jsonable(value) for key, value in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_jsonable(value) for value in obj]
    if isinstance(obj, (np.integer,)):
        return int(obj)
    if isinstance(obj, (np.floating,)):
        obj = float(obj)
    if isinstance(obj, float):
        # JSON has no NaN/Infinity literals: a non-finite number becomes null.
        return obj if math.isfinite(obj) else None
    if isinstance(obj, np.ndarray):
        return obj.tolist()
    if isinstance(obj, (str, int, float, bool)) or obj is None:
        return obj
    return str(obj)


def write_json(analysis: dict, path: str) -> None:
    directory = os.path.dirname(path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(_jsonable(analysis), fh, indent=2)
        fh.write("\n")


def markdown(analysis: dict) -> str:
    """Render the scientific summary from the computed analysis."""
    audit = analysis["audit"]
    slopes = analysis["slopes"]
    equal = analysis["equal_steps"]
    budget = analysis["budget"]
    scaling = analysis["scaling"]
    mins = analysis["min_resources"]
    reliability = analysis["reliability"]
    findings = analysis["findings"]
    ns = audit["n_values"]

    lines: list[str] = []
    add = lines.append

    add("# Phase 2 - accuracy versus circuit resources\n")
    add("Generated by `python -m analysis.run_phase2` from the committed Phase 1 measurements")
    add("(`results/circuit_resources.csv`)")
    if "supplementary" in audit["sources"]:
        add("plus the supplementary sweep at larger `r` (`results/phase2/supplementary_sweep.csv`),")
        add("which uses the same propagator via `trotter.sweep` - no value here is extrapolated.")
    else:
        add("only; no supplementary data was loaded.")
    add("")

    # -- data ---------------------------------------------------------------
    add("## 1. Data audited\n")
    add(f"* Rows usable: **{audit['rows']}**; row-level problems: **{len(audit['row_problems'])}**.")
    add(f"* Qubit counts: {audit['n_values']}; formula orders: {audit['orders']}.")
    add(f"* Step counts: {len(audit['r_values'])} values from {min(audit['r_values'])} "
        f"to {max(audit['r_values'])}.")
    add(f"* Error metric: `{audit['error_metric']}` (operator norm of the propagator difference).")
    add(f"* Counting convention: {audit['counting_convention']}.")
    add(f"* Depth: {audit['depth_definition']}.")
    add(f"* Every row carries consistent resources: **{audit['every_row_has_resources']}**.")
    add(f"* Numerical floor used to flag round-off: `{audit['numerical_floor']:g}`.\n")

    add("| configuration | rows | r range | error at smallest r | error at largest r | strictly decreasing | at floor |")
    add("|---|---|---|---|---|---|---|")
    for key, cfg in audit["configs"].items():
        add(f"| {key} | {cfg['rows']} | {cfg['r_min']}-{cfg['r_max']} | "
            f"{_fmt(cfg['error_first'])} | {_fmt(cfg['error_last'])} | "
            f"{cfg['strictly_decreasing']} | {cfg['at_numerical_floor']} |")
    add("")

    # -- findings -----------------------------------------------------------
    add("## 2. Findings\n")
    for finding in findings:
        add(f"* {finding}")
    add("")

    # -- accuracy per resource ---------------------------------------------
    add("## 3. Error versus circuit resources\n")
    add("| configuration | slope of log(error) vs log(CNOT) | interpretation |")
    add("|---|---|---|")
    for (n, order), slope in sorted(slopes.items()):
        add(f"| n={n}, {order} | {slope:+.2f} | "
            f"one decade of CNOTs buys {abs(slope):.1f} decades of accuracy |")
    add("")
    add("A slope of about -1 means error falls like `1/CNOT`; -2 means `1/CNOT^2`, i.e. the")
    add("second-order formula converts entangling gates into accuracy quadratically faster.")
    add("")

    # -- equal steps --------------------------------------------------------
    add("## 4. Equal Trotter step count\n")
    for n in ns:
        rows = equal.get(str(n)) or equal.get(n) or []
        if not rows:
            continue
        first, last = rows[0], rows[-1]
        add(f"### n = {n}\n")
        add(f"At `r = {first['r']}`: error {_fmt(first['error_order1'])} -> "
            f"{_fmt(first['error_order2'])}, CNOT {first['cnot_order1']} -> "
            f"{first['cnot_order2']} (+{_fmt(first['cnot_overhead_pct'], 3)}%), "
            f"total gates {first['total_order1']} -> {first['total_order2']} "
            f"(+{_fmt(first['gate_overhead_pct'], 3)}%).")
        add(f"At `r = {last['r']}`: error {_fmt(last['error_order1'])} -> "
            f"{_fmt(last['error_order2'])}, CNOT {last['cnot_order1']} -> "
            f"{last['cnot_order2']} (+{_fmt(last['cnot_overhead_pct'], 3)}%), "
            f"total gates {last['total_order1']} -> {last['total_order2']} "
            f"(+{_fmt(last['gate_overhead_pct'], 3)}%).")
        add("")
    add("The overhead shrinks as `r` grows because it is the fixed `2(n-1)` CNOT and")
    add("`3(n-1)` gate cost of the two merged end half-layers, not a per-step cost.\n")

    # -- equal budgets ------------------------------------------------------
    add("## 5. Equal resource budgets\n")
    for metric, label in (("cnot", "CNOT"), ("total_gates", "total gates")):
        add(f"### Equal {label} budget\n")
        for n in ns:
            rows = budget[metric].get(str(n)) or budget[metric].get(n) or []
            if not rows:
                continue
            red = [row["error_reduction_pct_interpolated"] for row in rows
                   if row["error_reduction_pct_interpolated"] == row["error_reduction_pct_interpolated"]]
            gaps = [abs(row["budget_gap_pct"]) for row in rows
                    if row["budget_gap_pct"] == row["budget_gap_pct"]]
            if not red:
                continue
            add(f"* n={n}: at matched budgets, second order is better by "
                f"**{min(red):.1f}% to {max(red):.1f}%** in error "
                f"(median {float(np.median(red)):.1f}%); the nearest measured first-order "
                f"configuration differs in budget by at most {max(gaps):.1f}%.")
        add("")
    add("The matched-budget first-order errors are log-log interpolations between two measured")
    add("neighbours (triangles in the figures); the nearest measured configuration is reported")
    add("alongside every interpolated value, so the conclusion does not rest on interpolation.\n")

    # -- scaling ------------------------------------------------------------
    add("## 6. Scaling with qubit count and step count\n")
    add(f"* Analytical formulas reproduced by every measured row: "
        f"max |difference| = {_fmt(scaling['verification']['max_abs_difference'])} "
        f"over {scaling['verification']['rows_checked']} rows "
        f"(all match: {scaling['verification']['all_match']}).")
    for order in (1, 2):
        stats = scaling["by_order"].get(str(order)) or scaling["by_order"].get(order)
        if not stats:
            continue
        add(f"* Order {order}: CNOT vs (n-1) slope {stats['cnot_vs_bonds']:+.2f} "
            f"(theory +1.00); total gates vs r slope {stats['total_vs_r']:+.2f} "
            f"(theory +1.00); depth vs r slope {stats['depth_vs_r']:+.2f}; "
            f"depth vs (n-1) slope {stats['depth_vs_bonds']:+.2f}.")
    spread = scaling.get("depth_spread", {})
    for order, info in spread.items():
        add(f"* Order {order}: at fixed r=200 the depth varies by only "
            f"{info['spread_pct']:.2f}% between the smallest and largest chain "
            f"({info['depth']}).")
    add("")
    add("So gate counts scale linearly in `(n-1)` and linearly in `r`; depth scales linearly in")
    add("`r` but is almost independent of `n`, because the chain is simulated sequentially bond by")
    add("bond and no bond parallelism is exploited by the conservative scheduler.\n")

    # -- targets ------------------------------------------------------------
    add("## 7. Minimum resources for a target accuracy\n")
    add(analysis["min_resources_markdown"])
    add("")
    missing = [row for row in mins if not row["achieved"]]
    if missing:
        add(f"{len(missing)} of {len(mins)} requested thresholds were **not** reached by any "
            f"measured configuration and are marked `{accuracy_targets.NOT_ACHIEVED}`.")
    else:
        add("Every requested threshold was reached by a measured configuration, so no cell in this")
        add("table required extrapolation.")
    add("Every row is a measured configuration; the `selected_by` column says whether it is the")
    add("cheapest by CNOT count or by total gate count.\n")

    reached = analysis["min_resources_pairs"]
    add("### Savings where both formulas reach the same target\n")
    add("| n | target | CNOT (1st) | CNOT (2nd) | CNOT saving | gates (1st) | gates (2nd) | gate saving |")
    add("|---|---|---|---|---|---|---|---|")
    for entry in reached:
        if not entry["achieved_by_both"]:
            add(f"| {entry['n']} | {entry['target_error']:g} | - | - | - | - | - | "
                f"{entry['note']} |")
            continue
        add(f"| {entry['n']} | {entry['target_error']:g} | {entry['cnot_order1']} | "
            f"{entry['cnot_order2']} | {entry['cnot_savings_pct']:.1f}% | "
            f"{entry['gates_order1']} | {entry['gates_order2']} | "
            f"{entry['gate_savings_pct']:.1f}% |")
    add("")
    add("Positive savings mean the second-order formula needs fewer resources for the same")
    add("accuracy. This is a resource-efficiency statement, not a claim of quantum advantage.\n")

    # -- reliability --------------------------------------------------------
    add("## 8. Numerical reliability\n")
    add(f"* Rows at or below the numerical floor: **{reliability['at_floor']}** "
        f"(floor = {audit['numerical_floor']:g}).")
    add(f"* Smallest measured operator error: {_fmt(reliability['min_error'])}.")
    add(f"* Strictly decreasing curves: {reliability['monotone_configs']} of "
        f"{len(audit['configs'])}; non-monotone steps: {reliability['nonmonotone_steps']}.")
    add(f"* Non-positive errors in the data: {reliability['zero_errors']} "
        f"(plots clip at {reliability['plot_floor']:g} without touching the CSV).")
    add(f"* Raw values preserved: `results/circuit_resources.csv` is read-only for Phase 2; "
        f"supplementary values live in a separate file.\n")

    # -- limits -------------------------------------------------------------
    add("## 9. Limits of these conclusions\n")
    add("* Gate counts are logical and assume all-to-all connectivity; no compilation, native gate")
    add("  set or error-correction overhead is modelled.")
    add("* Depth is one conservative ASAP schedule (no bond colouring, no hardware timing);")
    add("  differences of a few percent in depth are not meaningful.")
    add("* Only `n = 4, 5, 6` and `t = 1, J = h = 1` were measured; nothing here is extrapolated")
    add("  beyond that range, and no claim is made about larger systems.")
    add("* Errors near the floor are round-off, not physical accuracy.")
    add("* No noise model: these are ideal-simulation costs, not device predictions.\n")

    add("## 10. Files\n")
    for name, description in analysis["outputs"].items():
        add(f"* `{name}` - {description}")
    add("")
    return "\n".join(lines)
